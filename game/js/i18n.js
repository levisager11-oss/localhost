let lang = "en";
export const getLang = () => lang;
export function setLang(l) {
  lang = l === "de" ? "de" : "en";
}
/** The language the browser asks for. */
export function browserLang() {
  const l = (typeof navigator !== "undefined" && (navigator.languages?.[0] || navigator.language)) || "en";
  return /^de\b/i.test(l) ? "de" : "en";
}

/**
 * A text of an upgrade. The two upgrades every machine has share their texts: the machine's
 * name is filled in, and the joke is one of a few. New versions of localhost work the same way.
 */
export function upgradeText(u, field) {
  if (u.kind === "release") return t(field === "desc" ? `up.release.desc${u.index % 4}` : `up.release.${field}`, { v: `${u.version}.0` });
  if (!u.tier) return t(`up.${u.id}.${field}`);
  const key = field === "desc" ? `up.${u.kind}.desc${u.index % 4}` : `up.${u.kind}.${field}`;
  return t(key, { name: t(`hw.${u.tier}.name`) });
}

/** A text in the current language, with {name} parts filled in. */
export function t(key, params) {
  let s = TEXTS[lang][key] ?? TEXTS.en[key] ?? key;
  if (params) for (const k in params) s = s.replaceAll(`{${k}}`, params[k]);
  return s;
}
